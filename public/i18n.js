function dlDefaultLang() {
  try {
    const langs = navigator.languages || [navigator.language || ''];
    if (langs.some(l => l && l.toLowerCase().startsWith('ko'))) return 'ko';
  } catch (e) {}
  return 'en';
}
function dlLang() {
  return localStorage.getItem('dl_lang') || dlDefaultLang();
}
function dlT(key) {
  const entry = DL_I18N[key];
  if (!entry) return key;
  return entry[dlLang()] || entry.en;
}
function dlApplyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = dlT(el.getAttribute('data-i18n')); });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = dlT(el.getAttribute('data-i18n-placeholder')); });
  scope.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = dlT(el.getAttribute('data-i18n-html')); });
  scope.querySelectorAll('[data-i18n-aria-label]').forEach(el => { el.setAttribute('aria-label', dlT(el.getAttribute('data-i18n-aria-label'))); });
  document.querySelectorAll('.lang-switch [data-lang]').forEach(b => {
    b.classList.toggle('on', b.getAttribute('data-lang') === dlLang());
  });
}
function dlSetLang(lang) {
  localStorage.setItem('dl_lang', lang);
  dlApplyI18n();
  if (typeof window.dlOnLangChange === 'function') window.dlOnLangChange(lang);
}
function dlLangSwitchHtml() {
  const cur = dlLang();
  return `<span class="lang-switch">
    <button data-lang="en" class="${cur==='en'?'on':''}" onclick="dlSetLang('en')">EN</button>
    <button data-lang="ko" class="${cur==='ko'?'on':''}" onclick="dlSetLang('ko')">한국어</button>
  </span>`;
}
document.addEventListener('DOMContentLoaded', () => dlApplyI18n());
